numbers = [42, 7, 19, 88, 11]

# Length of a list
print("Number of items:", len(numbers))

# Max, Min, and Sum
print("Highest number:", max(numbers))
print("Lowest number:", min(numbers))
print("Total sum:", sum(numbers))

# Sorting
numbers.sort()  # Sorts the original list in ascending order
print("Sorted list:", numbers)

numbers.reverse()  # Reverses the order of the list
print("Reversed list:", numbers)
